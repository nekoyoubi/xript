// Regenerates src/Xript.Runtime/Expressions/CaseTables.cs from the host's Unicode data.
// XEG's `upper` and `lower` use Unicode's default full case mapping. .NET only exposes the
// simple (one-to-one) mapping and lags a Unicode version, so the C# runtime carries the
// full mapping as data instead of asking the framework.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, "../src/Xript.Runtime/Expressions/CaseTables.cs");

const upper = [];
const lower = [];
const cased = [];
const ignorable = [];
const casedRe = /^\p{Cased}$/u;
const ignorableRe = /^\p{Case_Ignorable}$/u;

function pushRange(ranges, cp) {
	const last = ranges[ranges.length - 1];
	if (last && last[1] === cp - 1) last[1] = cp;
	else ranges.push([cp, cp]);
}

for (let cp = 0; cp <= 0x10ffff; cp++) {
	if (cp >= 0xd800 && cp <= 0xdfff) continue;
	const c = String.fromCodePoint(cp);
	const up = [...c.toUpperCase()].map((ch) => ch.codePointAt(0));
	const low = [...c.toLowerCase()].map((ch) => ch.codePointAt(0));
	if (up.length !== 1 || up[0] !== cp) upper.push([cp, up]);
	if (low.length !== 1 || low[0] !== cp) lower.push([cp, low]);
	if (casedRe.test(c)) pushRange(cased, cp);
	if (ignorableRe.test(c)) pushRange(ignorable, cp);
}

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const mapEntries = (entries) => entries.map(([cp, to]) => `${hex(cp)}, ${to.length}, ${to.map(hex).join(", ")}`).join(",\n        ");
const rangeEntries = (ranges) => ranges.map(([a, b]) => `${hex(a)}, ${hex(b)}`).join(",\n        ");

writeFileSync(
	outFile,
	`// Generated by scripts/generate-case-tables.mjs (Unicode ${process.versions.unicode}). Do not edit.

namespace Xript.Runtime.Expressions;

internal static class CaseTables
{
    public const string UnicodeVersion = "${process.versions.unicode}";

    /// <summary>Full uppercase mappings that are not the identity, as (code point, count, targets…) runs.</summary>
    public static readonly int[] Upper =
    [
        ${mapEntries(upper)}
    ];

    /// <summary>Full lowercase mappings that are not the identity, as (code point, count, targets…) runs.</summary>
    public static readonly int[] Lower =
    [
        ${mapEntries(lower)}
    ];

    /// <summary>Inclusive ranges with the Unicode Cased property.</summary>
    public static readonly int[] Cased =
    [
        ${rangeEntries(cased)}
    ];

    /// <summary>Inclusive ranges with the Unicode Case_Ignorable property.</summary>
    public static readonly int[] CaseIgnorable =
    [
        ${rangeEntries(ignorable)}
    ];
}
`,
);
console.log(`case tables: ${upper.length} upper, ${lower.length} lower, ${cased.length} cased ranges, ${ignorable.length} ignorable ranges`);
