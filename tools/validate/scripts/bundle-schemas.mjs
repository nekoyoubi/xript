import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const specDir = resolve(here, "../../../spec");
const outFile = resolve(here, "../src/generated/schemas.ts");

const files = [
	"manifest.schema.json",
	"mod-manifest.schema.json",
	"capability-prompt.schema.json",
	"install-descriptor.schema.json",
	"discovery-result.schema.json",
	"debug-messages.schema.json",
];
for (const family of ["manifest", "mod-manifest"]) {
	for (const file of (await readdir(resolve(specDir, "history", family))).sort()) {
		if (file.endsWith(".json")) files.push(`history/${family}/${file}`);
	}
}

const entries = [];
for (const relative of files) {
	const text = await readFile(resolve(specDir, relative), "utf-8");
	entries.push(`\t${JSON.stringify(relative)}: ${JSON.stringify(JSON.stringify(JSON.parse(text)))},`);
}

await mkdir(dirname(outFile), { recursive: true });
await writeFile(
	outFile,
	[
		"// Generated by scripts/bundle-schemas.mjs from spec/. Do not edit.",
		"export const BUNDLED_SCHEMA_SOURCES: Readonly<Record<string, string>> = {",
		...entries,
		"};",
		"",
	].join("\n"),
);
